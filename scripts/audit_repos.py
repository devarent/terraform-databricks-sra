#!/usr/bin/env python3
"""Read-only public repository inventory using gh; no third-party Python packages."""
import argparse
from concurrent.futures import ThreadPoolExecutor
from datetime import datetime, timezone
import json
from pathlib import Path
import re
import subprocess
import sys


class ApiError(RuntimeError):
    pass


def api(endpoint, *, paginate=False, optional=False):
    command = ["gh", "api", endpoint]
    if paginate:
        command += ["--paginate", "--jq", ".[] | @json"]
    result = subprocess.run(command, capture_output=True, text=True, check=False)
    if result.returncode:
        # Only a confirmed 404 is absence. Authentication/rate limits are errors.
        try:
            status = json.loads(result.stdout).get("status")
        except (ValueError, AttributeError):
            status = None
        if optional and str(status) == "404":
            return None
        raise ApiError(f"{endpoint}: {result.stderr.strip() or 'GitHub API failed'}")
    try:
        data = ([json.loads(line) for line in result.stdout.splitlines() if line.strip()]
                if paginate else json.loads(result.stdout))
    except ValueError as exc:
        raise ApiError(f"{endpoint}: invalid JSON") from exc
    return data


def inspect(repo):
    base = f"repos/{repo['full_name']}"
    row = {key: repo.get(key) for key in (
        "name", "full_name", "html_url", "description", "language", "topics",
        "fork", "archived", "default_branch", "size", "open_issues_count", "pushed_at"
    )}
    row["license_spdx"] = (repo.get("license") or {}).get("spdx_id")
    row["errors"] = []
    for field, endpoint in (("readme", "/readme"), ("root", "/contents/"),
                            ("workflows", "/contents/.github/workflows")):
        try:
            data = api(base + endpoint, optional=True)
            if field == "readme":
                row["readme"] = data["name"] if data else None
            else:
                # A directory listing counts files only, not subdirectories/README.
                files = [entry["name"] for entry in (data or []) if entry["type"] == "file"]
                if field == "root":
                    row["license_files"] = sorted(n for n in files if re.fullmatch(
                        r"licen[cs]e(?:\..+)?|copying(?:\..+)?", n, re.I))
                    row["gitignore"] = ".gitignore" in files
                else:
                    row["workflow_files"] = sorted(n for n in files if n.endswith((".yml", ".yaml")))
        except ApiError as exc:
            row["errors"].append(str(exc))
    return row


def cell(value):
    return str(value if value is not None else "—").replace("|", "\\|").replace("\n", " ").replace("\r", " ").replace("<", "&lt;").replace(">", "&gt;")


def render(snapshot):
    rows = snapshot["repositories"]
    text = [f"# Repository Atlas — @{snapshot['owner']}", "",
            f"Snapshot UTC: {snapshot['fetched_at']}. Total: **{len(rows)} public repositories**.", "",
            "Generated by `python3 scripts/audit_repos.py --write`. Source: GitHub REST API, all pages.",
            "See [audit and follow-ups](AUDIT-2026-11-22.md). Raw evidence: [REPO-ATLAS.json](REPO-ATLAS.json).", "",
            "## Scope and interpretation", "",
            "- This is a read-only metadata/file-presence audit, **not** a code, security, or runtime certification.",
            "- Workflow count means YAML files present, not enabled workflows or passing runs. Commented-out files can be counted.",
            "- License detection is not legal advice: `NOASSERTION` means no SPDX match; `—` means no detected license. Read the actual license.",
            "- `open_issues_count` includes pull requests. Branch names, repository size and forks are context, not defects.",
            "- Missing files are reported only after HTTP 404 or a successful directory listing. Other API errors are **unknown**.",
            "- Public repositories only; no private repository discovery or remote writes.", "",
            "## All repositories", "",
            "| # | Repository | Description | Language | SPDX | Default branch | Fork | Size (GitHub KB) | Open issues + PRs |",
            "|---|---|---|---|---|---|---|---|---|"]
    for i, r in enumerate(rows, 1):
        text.append(f"| {i} | [{r['name']}]({r['html_url']}) | {cell(r['description'])} | {cell(r['language'])} | {cell(r['license_spdx'])} | {cell(r['default_branch'])} | {'yes' if r['fork'] else 'no'} | {r['size']} | {r['open_issues_count']} |")
    text += ["", "## File-presence matrix", "",
             "| Repository | README | License filenames | .gitignore | Workflow YAML files | API errors |",
             "|---|---|---|---|---|---|"]
    for r in rows:
        readme = cell(r.get("readme", "unknown"))
        licenses = ", ".join(r["license_files"]) or "none at root" if "license_files" in r else "unknown"
        gi = ("yes" if r["gitignore"] else "no") if "gitignore" in r else "unknown"
        wf = str(len(r["workflow_files"])) if "workflow_files" in r else "unknown"
        text.append(f"| {r['name']} | {readme} | {cell(licenses)} | {gi} | {wf} | {len(r['errors'])} |")
    text += ["", "## Refresh", "", "```bash", "bash scripts/audit-repos.sh --write", "```", "",
             "Requires Python 3 and an authenticated `gh` CLI. Without `--write`, JSON goes to stdout.",
             "The Markdown atlas and JSON snapshot are regenerated together; the narrative audit is reviewed manually.",
             "API failures produce unknown fields and a nonzero exit status, never a false clean result.", ""]
    return "\n".join(text)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--owner", default="devarent")
    parser.add_argument("--write", action="store_true", help="Write docs/REPO-ATLAS.{json,md}")
    args = parser.parse_args()
    if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9-]{0,38}", args.owner):
        parser.error("invalid GitHub owner")
    try:
        repos = api(f"users/{args.owner}/repos?per_page=100&type=owner", paginate=True)
        with ThreadPoolExecutor(max_workers=4) as pool:
            rows = list(pool.map(inspect, sorted(repos, key=lambda r: r["name"].lower())))
    except (ApiError, OSError) as exc:
        print(f"Audit failed: {exc}", file=sys.stderr)
        return 1
    snapshot = {"owner": args.owner, "fetched_at": datetime.now(timezone.utc).isoformat(),
                "repositories": rows}
    output = json.dumps(snapshot, ensure_ascii=False, indent=2) + "\n"
    if args.write:
        docs = Path(__file__).resolve().parent.parent / "docs"
        (docs / "REPO-ATLAS.json").write_text(output, encoding="utf-8")
        (docs / "REPO-ATLAS.md").write_text(render(snapshot), encoding="utf-8")
    else:
        print(output, end="")
    failures = sum(len(row["errors"]) for row in rows)
    print(f"Inspected {len(rows)} repositories; {failures} API errors.", file=sys.stderr)
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
